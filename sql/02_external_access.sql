-- Egress for the lab bundles: only this account's host (gateway inference, gateway OTLP,
-- Cortex Training API). Package/tokenizer downloads reuse CT_QUICKSTART_DOWNLOAD_EAI.
USE ROLE ACCOUNTADMIN;
CREATE EXTERNAL ACCESS INTEGRATION IF NOT EXISTS AGT_LAB_API_EAI
  ALLOWED_NETWORK_RULES = (CT_QUICKSTART_DB.LAB.CT_ACCOUNT_RULE)
  ALLOWED_AUTHENTICATION_SECRETS = (CT_QUICKSTART_DB.AGT.AGT_PAT)
  ENABLED = TRUE;
GRANT USAGE ON INTEGRATION AGT_LAB_API_EAI TO ROLE CT_QUICKSTART_USER;
GRANT USAGE ON INTEGRATION CT_QUICKSTART_DOWNLOAD_EAI TO ROLE CT_QUICKSTART_USER;
GRANT CREATE CODE BUNDLE ON SCHEMA CT_QUICKSTART_DB.AGT TO ROLE CT_QUICKSTART_USER;
